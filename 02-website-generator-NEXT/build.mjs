/**
 * Emit the single-file generator: `generator.html`.
 *
 * The source stays eleven ES modules — the test suite imports them directly in
 * Node and nothing here changes that. This script flattens them into one
 * inlined <script type="module">, so the file opens by double-click with no
 * server and no Node, exactly like the legacy generator.
 *
 * Each module is wrapped in its own IIFE and parks its exports on a registry.
 * That is not decoration: flattened into one scope the modules collide on four
 * names (T, page, doc, S), and renaming them would mean touching source that
 * currently works. A registry makes a collision impossible by construction.
 *
 *   node build.mjs
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, "src");
const OUT = join(ROOT, "dist");

/**
 * Module order, derived from the import graph rather than written down.
 *
 * A hand-written list is a landmine: adding a module and forgetting to add it
 * here produces a bundle that throws on the first line and looks fine until you
 * open it. Sorting the real graph means ui.js is always last, `presets.js` lands
 * before `templates.js` on its own, and a new file needs no edit here at all.
 */
const dir = join(SRC, "js");
const files = readdirSync(dir).filter((f) => f.endsWith(".js"));
const deps = new Map();
for (const f of files) {
  const src = readFileSync(join(dir, f), "utf8");
  deps.set(f, [...src.matchAll(/from\s+"\.\/([^"]+\.js)"/g)].map((m) => m[1]));
}

const ORDER = [];
const state = new Map();          // unseen / visiting / done
function visit(f, trail) {
  if (state.get(f) === "done") return;
  if (state.get(f) === "visiting") {
    throw new Error(`import cycle: ${[...trail, f].join(" -> ")}`);
  }
  state.set(f, "visiting");
  for (const d of deps.get(f) || []) {
    if (!deps.has(d)) throw new Error(`${f} imports ${d}, which is not in src/js`);
    visit(d, [...trail, f]);
  }
  state.set(f, "done");
  ORDER.push(f);
}
for (const f of files) visit(f, []);
if (ORDER.length !== files.length) throw new Error("some modules were never reached");

/** Names each module exports, and the local name behind any `a as b` alias. */
function exportsOf(src) {
  const names = [];
  const local = {};
  for (const m of src.matchAll(/^export\s+(?:const|let|var|function|class|async function)\s+([A-Za-z0-9_$]+)/gm)) {
    names.push(m[1]);
  }
  for (const m of src.matchAll(/^export\s*\{([^}]*)\}/gm)) {
    for (const item of m[1].split(",").map((s) => s.trim()).filter(Boolean)) {
      const parts = item.split(/\s+/);
      if (parts.length >= 3) { names.push(parts[2]); local[parts[2]] = parts[0]; }
      else names.push(parts[0]);
    }
  }
  return names.map((n) => (local[n] ? `${n}: ${local[n]}` : n));
}

/** One module: imports become registry reads, exports become the return value. */
function flatten(name) {
  let src = readFileSync(join(SRC, "js", name), "utf8");

  const returns = exportsOf(src);

  src = src.replace(/^import\s+\{([^}]*)\}\s+from\s+"\.\/([^"]+)";?[ \t]*$/gm,
    (whole, clause, from) => {
      const names = clause.split(",").map((s) => s.trim()).filter(Boolean)
        .map((s) => s.replace(/\s+as\s+/, ": "));
      return `const { ${names.join(", ")} } = __m[${JSON.stringify(from)}];`;
    });

  src = src.replace(/^export\s*\{[^}]*\};?[ \t]*$/gm, "");
  src = src.replace(/^export\s+(?=(?:const|let|var|function|class|async function)\s)/gm, "");

  const leftover = src.match(/^\s*(?:import|export)\s/m);
  if (leftover) throw new Error(`${name}: an import/export survived the transform`);

  return `__m[${JSON.stringify(name)}] = (() => {\n${src}\nreturn { ${returns.join(", ")} };\n})();`;
}

const bundle = [
  "/* Website Generator Next — single-file build. Generated by build.mjs;",
  "   edit src/js/*.js, never this file. */",
  "const __m = {};",
  ...ORDER.map(flatten)
].join("\n");

// A literal </script> inside a string would close the tag early. Inside a JS
// string, "</script>" and "<\\/script>" are the same value, so this is safe.
const safeBundle = bundle.replace(/<\/script/gi, "<\\/script");

const css = readFileSync(join(SRC, "app.css"), "utf8");
const html = readFileSync(join(SRC, "index.html"), "utf8");

const out = html
  .replace('<link rel="stylesheet" href="app.css">', `<style>\n${css}\n</style>`)
  .replace('<script type="module" src="js/ui.js"></script>', `<script type="module">\n${safeBundle}\n</script>`);

if (out.includes('src="js/ui.js"') || out.includes('href="app.css"')) {
  throw new Error("the shell still points at external files — the build did not inline them");
}
if (out.includes("</script>\n</body>") === false && !out.trimEnd().endsWith("</html>")) {
  throw new Error("the emitted document does not look well formed");
}

mkdirSync(OUT, { recursive: true });
const file = join(OUT, "generator.html");
writeFileSync(file, out, "utf8");

console.log(`built ${file}`);
console.log(`  ${ORDER.length} modules, ${(bundle.length / 1024).toFixed(0)} KB of JS`);
console.log(`  ${(css.length / 1024).toFixed(0)} KB of CSS`);
console.log(`  ${(out.length / 1024).toFixed(0)} KB total`);